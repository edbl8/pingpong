void get_temp(float *pixels){
  HAL_StatusTypeDef status;

  uint8_t raw[128];

  status = HAL_I2C_Mem_Read(&hi2c1, AMG8833_ADDR, 0x80, I2C_MEMADD_SIZE_8BIT, raw, 128, 100);

    for(int i = 0; i < 64; i++)
    {
        uint16_t rawValue;
        int16_t signedValue;

        rawValue = raw[i * 2] | (raw[i * 2 + 1] << 8);

        // 12-bit signed conversion
        if(rawValue & 0x800)
        {
            signedValue = rawValue - 4096;
        }
        else
        {
            signedValue = rawValue;
        }

        pixels[i] = signedValue * 0.25f;
    }
  
}

uint16_t get_color_temp(float temp){
  if (temp < 21) return ILI9341_BLUE;
  if (temp < 22.5) return ILI9341_CYAN;
  if (temp < 23.5) return ILI9341_YELLOW;
  if (temp < 25) return ILI9341_MAGENTA;
  return ILI9341_RED;
}

